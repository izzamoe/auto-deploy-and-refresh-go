package admin

import (
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/izzamoe/auto-deploy/internal/deploy"
	"github.com/izzamoe/auto-deploy/internal/store"
)

// T046 (B14, Q-10): DELETE /admin/api/v1/apps/{id} removes the app with its env, args
// and jobs; ?removeUnitFile=true additionally removes the GENERATED unit file; the
// default leaves it.

const generatedMarker = "# Generated by auto-deploy -- safe to regenerate; hand edits will be lost on next apply"

func TestDeleteAppAPI_RemovesEnvArgsAndUnitFileOnlyOnRequest(t *testing.T) {
	h, appStore, queue, jwt := newTestAdminAPIHertz(t)
	envs, err := store.NewAppEnvStore(appStore.DB())
	if err != nil {
		t.Fatal(err)
	}
	args, err := store.NewAppArgsStore(appStore.DB())
	if err != nil {
		t.Fatal(err)
	}
	unitDir := t.TempDir()
	defer deploy.SetSystemdUnitDirForTest(unitDir)()
	defer deploy.SetRunSystemctlForTest(func(string, ...string) ([]byte, error) { return nil, nil })()

	mk := func(name string) string {
		app, err := appStore.Create(name, "secret-"+name, "/opt/"+name+"/"+name, name+".service", "o/"+name, name)
		if err != nil {
			t.Fatal(err)
		}
		if err := envs.Set(app.ID, []store.EnvVar{{Name: "BOT_TOKEN", Value: "123:SECRET"}}); err != nil {
			t.Fatal(err)
		}
		if err := args.Set(app.ID, []string{"--port", "1"}); err != nil {
			t.Fatal(err)
		}
		if err := queue.Enqueue(app.ID, "v1"); err != nil {
			t.Fatal(err)
		}
		unit := filepath.Join(unitDir, name+".service")
		if err := os.WriteFile(unit, []byte(generatedMarker+"\n[Service]\nExecStart=/x\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		return app.ID
	}
	del := func(id, query string) (int, string) {
		c := serveAdminAPIHertz(t, h, adminAPIRequestHertz(jwt, "DELETE", "/admin/api/v1/apps/"+id+query, ""))
		return c.Response.StatusCode(), string(c.Response.Body())
	}
	exists := func(name string) bool {
		_, err := os.Stat(filepath.Join(unitDir, name+".service"))
		return err == nil
	}

	keep := mk("keepunit")
	if code, body := del(keep, ""); code != http.StatusOK {
		t.Fatalf("default delete = %d %s", code, body)
	}
	if !exists("keepunit") {
		t.Error("the unit file must stay by default (Q-10: removeUnitFile defaults to false)")
	}
	if got, _ := envs.Get(keep); len(got) != 0 {
		t.Errorf("env of the deleted app still stored: %v", got)
	}
	if got, _ := args.Get(keep); len(got) != 0 {
		t.Errorf("args of the deleted app still stored: %v", got)
	}

	drop := mk("dropunit")
	if code, body := del(drop, "?removeUnitFile=true"); code != http.StatusOK || !strings.Contains(body, "unit file removed") {
		t.Fatalf("delete with removeUnitFile=true = %d %s", code, body)
	}
	if exists("dropunit") {
		t.Error("?removeUnitFile=true must remove the generated unit file")
	}

	// A hand-written unit is never removed; the app is still deleted and the answer says so.
	hand := mk("handunit")
	if err := os.WriteFile(filepath.Join(unitDir, "handunit.service"), []byte("[Service]\nExecStart=/mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	code, body := del(hand, "?removeUnitFile=true")
	if code != http.StatusOK || strings.Contains(body, "unit file removed") || !strings.Contains(body, "could not be removed") {
		t.Fatalf("delete over a hand-written unit = %d %s", code, body)
	}
	if !exists("handunit") {
		t.Error("a hand-written unit file must never be removed")
	}
	if _, err := appStore.Get(hand); err == nil {
		t.Error("the app must still be deleted when the unit file could not be removed")
	}

	// Bad query value -> 400 validation_failed, nothing deleted.
	other := mk("badquery")
	if code, body := del(other, "?removeUnitFile=maybe"); code != http.StatusBadRequest || !strings.Contains(body, "validation_failed") {
		t.Fatalf("removeUnitFile=maybe = %d %s, want 400 validation_failed", code, body)
	}
	if _, err := appStore.Get(other); err != nil {
		t.Errorf("an invalid request must delete nothing: %v", err)
	}
}
